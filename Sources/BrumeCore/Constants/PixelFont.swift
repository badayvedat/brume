import Foundation

/// Une police de 5 × 7 pixels pour écrire un mot en grosses lettres sur l'écran de démarrage.
/// Les minuscules s'écrivent en capitales, les accents tombent, le reste est ignoré.
public enum PixelFont {
    public static let height = 7

    public static func supported(_ text: String) -> String {
        String(text.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: nil).uppercased().filter { glyphs[$0] != nil })
    }

    public static func glyph(_ character: Character) -> [String]? {
        glyphs[character]
    }

    /// Le mot en pixels, à l'échelle donnée, en dégradé de l'accent avec une ombre (lettres de `PixelArt`).
    public static func banner(_ text: String, scale: Int) -> [String] {
        let glyphs = supported(text).compactMap(glyph)
        guard !glyphs.isEmpty else { return [] }
        let width = glyphs.reduce(0) { $0 + ($1[0].count + 1) * scale } - scale + 1
        let height = height * scale + 1
        var grid = Array(repeating: Array(repeating: Character("."), count: width), count: height)
        var x = 0
        for glyph in glyphs {
            for (row, line) in glyph.enumerated() {
                let shade: Character = row < 2 ? "L" : row < 5 ? "A" : "D"
                for (column, pixel) in line.enumerated() where pixel == "#" {
                    for dy in 0 ..< scale {
                        for dx in 0 ..< scale {
                            grid[row * scale + dy][x + column * scale + dx] = shade
                        }
                    }
                }
            }
            x += (glyph[0].count + 1) * scale
        }
        var shadowed = grid
        for y in 0 ..< height - 1 {
            for x in 0 ..< width - 1 where grid[y][x] != "." && shadowed[y + 1][x + 1] == "." {
                shadowed[y + 1][x + 1] = "O"
            }
        }
        return shadowed.map { String($0) }
    }

