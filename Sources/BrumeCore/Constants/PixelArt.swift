/// Les visuels de l'écran de démarrage en pixel art, un caractère par pixel. Deux pixels l'un sur
/// l'autre font une case du terminal, d'où des pixels carrés. Dessinés pour Brume.
///
/// `A` l'accent, `L` `D` `E` l'accent éclairci, assombri, très sombre ; `H` `W` `G` `S` du blanc
/// au gris, `O` le contour, `K` presque noir ; `Z` `Y` `y` l'or ; `.` vide.
public enum PixelArt {
    /// La couleur de chaque lettre.
    public static func colors(_ accent: Accent) -> [Character: String] {
        [
            "A": accent.hex,
            "L": ThemeColors.mix(accent.hex, "ffffff", 0.45),
            "D": ThemeColors.mix(accent.hex, "000000", 0.4),
            "E": ThemeColors.mix(accent.hex, "000000", 0.7),
            "H": "ffffff",
            "W": "ebebeb",
            "G": "c2c2cc",
            "S": "85858f",
            "O": "3c3c46",
            "K": "101014",
            "Z": "ffe49a",
            "Y": "f2c14e",
            "y": "b07d22",
        ]
    }

    /// Le dessin à sa taille normale, ou sa version petite, redessinée pour garder les visages.
    public static func pixels(for visual: WelcomeVisual, small: Bool = false) -> [String]? {
        if small {
            return switch visual {
            case .ghost: ghostSmall
            case .saturn: saturnSmall
            case .cloud: cloudSmall
            case .saucer: saucerSmall
            case .slime: slimeSmall
            case .gem: gemSmall
            case .moon: moonSmall
            case .mushroom: mushroomSmall
            case .turtle: turtleSmall
            case .breath: breathSmall
            case .prompt: promptSmall
            case .apple: nil
            }
        }
        return switch visual {
        case .ghost: ghost
        case .saturn: saturn
        case .cloud: cloud
        case .saucer: saucer
        case .slime: slime
        case .gem: gem
        case .moon: moon
        case .mushroom: mushroom
        case .turtle: turtle
        case .breath: breath
        case .prompt: prompt
        case .apple: nil
        }
    }

